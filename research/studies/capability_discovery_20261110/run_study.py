def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def pair_key(a, b):
    return tuple(sorted((a, b)))


def clique(names):
    return {pair_key(a, b) for a, b in itertools.combinations(names, 2)}


# Evaluation-only semantic oracle; none of these labels are passed to Discovery.
# These broad positives include synonyms, representation/parameter differences,
# constant quantities and opaque text: they expose the engine's coverage limits.
DEV_POSITIVES = clique(["bundle", "temperature", "renamed_field", "renamed_argument",
                       "integer_temperature"]) | {("bundle", "nested_count"), ("constant_a", "constant_b")}
EXT_POSITIVES = clique(["inventory", "processor", "utilization_alias", "resource_load",
                       "fractional_load", "opaque"]) | {("inventory", "queue_depth")}


def score(decisions, positives, field):
    tp = fp = tn = fn = 0
    for result in decisions:
        actual = pair_key(result["left"], result["right"]) in positives
        prediction = result[field]
        tp += int(actual and prediction)
        fp += int(not actual and prediction)
        tn += int(not actual and not prediction)
        fn += int(actual and not prediction)
    return {"tp": tp, "fp": fp, "tn": tn, "fn": fn,
            "precision": tp / (tp + fp) if tp + fp else None,
            "recall": tp / (tp + fn) if tp + fn else None,
            "accuracy": (tp + tn) / len(decisions) if decisions else None,
            "false_positive_rate": fp / (fp + tn) if fp + tn else None}


def summarize(engine, positives):
    decisions = engine.discover()
    labels = [{"left": a, "right": b, "overlapping_information": pair_key(a, b) in positives}
              for a, b in itertools.combinations(sorted(engine.registry), 2)]
    return {"tools": len(engine.registry), "pairs": len(decisions),
            "semantic_positive_pairs": sum(row["overlapping_information"] for row in labels),
            "proposals": score(decisions, positives, "candidate"),
            "empirical_support": score(decisions, positives, "empirically_supported"),
            "asserted_semantic_equivalences": sum(r["semantic_equivalence"] != "unestablished" for r in decisions),
            "replacement_abstention_rate": sum(not r["replacement_allowed"] for r in decisions) / len(decisions),
            "false_supported_pairs": [[r["left"], r["right"]] for r in decisions
                                      if r["empirically_supported"] and pair_key(r["left"], r["right"]) not in positives],
            "decisions": decisions, "oracle_labels": labels, "rejections": engine.rejections}


def collect(engine, tools, items, phase, raw):
    count = 0
    for item in items:
        for registered in tools:
            # Fixture call inputs are supplied by the experiment, not discovered
            # or silently generated by the engine. All are reviewed pure functions.
            arguments = {next(iter(registered.args)): item}
            start = time.perf_counter_ns()
            output = registered.invoke(arguments)
            call_ns = time.perf_counter_ns() - start
            snapshot = f"synthetic-frozen-state:{item}"
            start = time.perf_counter_ns()
            accepted = engine.observe(registered.name, arguments, output,
                                      snapshot=snapshot, successful=True)
            ingest_ns = time.perf_counter_ns() - start
            raw.append({"phase": phase, "tool": registered.name, "arguments": arguments,
                        "snapshot": snapshot, "output": output, "accepted": accepted,
                        "tool_call_ns": call_ns, "observe_ns": ingest_ns})
            count += 1
    return count


def percentiles(values):
    ordered = sorted(values)
    return {"median_ms": statistics.median(ordered) / 1e6,
            "p95_ms": ordered[max(0, int(len(ordered) * .95 + .999999) - 1)] / 1e6,
            "samples_ns": values}


def scale_study():
    results = []
    for size in (10, 50, 100):
        tools = []
        for i in range(size):
            def reading(item: int) -> dict:
                return {"reading": float(item * 2 + 1)}
            tools.append(tool(f"synthetic_{i}", description="Read a synthetic scalar measurement.")(reading))
        refresh, observation, discovery = [], [], []
        for repeat in range(9):
            engine = Discovery()
            start = time.perf_counter_ns()
            engine.refresh(tools)
            refresh.append(time.perf_counter_ns() - start)
            start = time.perf_counter_ns()
            # Passive replay only: no tool invocations needed for this timing.
            for t in tools:
                for item in (0, 1, 4):
                    engine.observe(t.name, {"item": item}, {"reading": float(item * 2 + 1)},
                                   snapshot=f"scale:{item}", successful=True)
            observation.append(time.perf_counter_ns() - start)
            start = time.perf_counter_ns()
            engine.discover()
            discovery.append(time.perf_counter_ns() - start)
        results.append({"tools": size, "pairs": size * (size - 1) // 2, "observations": size * 3,
                        "repeats": 9, "refresh": percentiles(refresh),
                        "ingest_all": percentiles(observation), "discover_all_pairs": percentiles(discovery)})
    return results


def real_registry(raw):
    # Importing registries does not dispatch native ROS operations.
    from rosa.tools import ROSATools
    from rosa.tools import calculation
    registry = ROSATools(ros_version=2)
    engine = Discovery()
    engine.refresh(registry.get_tools())
    inventory = engine.inventory()
    metadata = engine.discover()
    # Fixed reviewed PURE subset; engine never chooses or probes functions.
    subset = [calculation.add_all, calculation.multiply_all, calculation.mean,
              calculation.median, calculation.variance]
    cases = [[1.0, 2.0, 3.0], [2.0, 3.0, 8.0], [-4.0, 0.0, 9.0], [5.0, 7.0, 12.0]]
    calc = Discovery()
    calc.refresh(subset)
    for i, numbers in enumerate(cases):
        for registered in subset:
            args = {"numbers": numbers}
            started = time.perf_counter_ns()
            output = registered.invoke(args)
            call_ns = time.perf_counter_ns() - started
            accepted = calc.observe(registered.name, args, output,
                                    snapshot=f"pure-case:{i}", successful=True)
            raw.append({"phase": "real_pure_calculation", "tool": registered.name,
                        "arguments": args, "snapshot": f"pure-case:{i}", "output": output,
                        "accepted": accepted, "tool_call_ns": call_ns})
    return {"registry": inventory, "tool_count": len(inventory),
            "informative_output_schemas": sum(bool(row["output_schema"].get("type")) for row in inventory),
            "metadata_only_proposal_count": sum(row["candidate"] for row in metadata),
            "metadata_only_empirical_support_count": sum(row["empirically_supported"] for row in metadata),
            "calculation": summarize(calc, set()), "pure_calculation_dispatches": len(cases) * len(subset),
            "native_ros_dispatches": 0}


def preservation():
    tracked = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).decode().split("\0")
    paths = [ROOT / p for p in tracked if p and (ROOT / p).is_file()]
    for directory in ("design", "diagnostics", "inbox"):
        paths.extend(p for p in (ROOT / "research" / directory).rglob("*") if p.is_file())
    return {"branch": subprocess.check_output(["git", "branch", "--show-current"], cwd=ROOT, text=True).strip(),
            "head": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
            "martin_remote": subprocess.check_output(["git", "rev-parse", "refs/remotes/origin/member/martin"], cwd=ROOT, text=True).strip(),
            "files": {str(p.relative_to(ROOT)): sha(p) for p in sorted(paths)}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=HERE / "results")
    parser.add_argument("--freeze", type=Path, default=HERE / "FREEZE_CORRECTED.json")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    if (args.output / "results.json").exists():
        raise SystemExit("Refusing to overwrite results; supply a fresh --output directory")
    freeze = json.loads(args.freeze.read_text())
    for name, expected in freeze["files"].items():
        if sha(HERE / name) != expected:
            raise SystemExit(f"Freeze mismatch: {name}")
    before = preservation()
    raw = []
    extra_calls = 0
    dev = Discovery()
    dev.refresh(development.TOOLS)
    dev_before = summarize(dev, DEV_POSITIVES)
    extra_calls += collect(dev, development.TOOLS, (0, 1, 4), "development", raw)
    dev_after = summarize(dev, DEV_POSITIVES)
    ext = Discovery()
    ext.refresh(extension.TOOLS)
    ext_before = summarize(ext, EXT_POSITIVES)
    extra_calls += collect(ext, extension.TOOLS, (0, 1, 4), "extension_initial", raw)
    ext_after = summarize(ext, EXT_POSITIVES)
    # Actual refresh of an already populated registry, using the same frozen engine.
    dev.refresh(development.TOOLS + extension.TOOLS)
    extra_calls += collect(dev, extension.TOOLS, (0, 1, 4), "new_registration", raw)
    newly_registered = summarize(dev, DEV_POSITIVES | EXT_POSITIVES)
    extra_calls += collect(ext, extension.TOOLS, (9,), "extension_counterexample", raw)
    ext_later = summarize(ext, EXT_POSITIVES)
    fallback_log = []
    lookup = {t.name: t for t in development.TOOLS + extension.TOOLS}
    def dispatch(name, inputs):
        fallback_log.append({"tool": name, "arguments": inputs})
        return lookup[name].invoke(inputs)
    for name, inputs in [("temperature", {"item": 6}), ("renamed_argument", {"index": 6}),
                         ("opaque", {"asset": 6}), ("processor", {"asset": 9})]:
        Discovery.ordinary_call(name, inputs, dispatch)
    native = real_registry(raw)
    scales = scale_study()
    result = {"protocol": "PROTOCOL.md", "freeze": freeze,
              "environment": {"python": platform.python_version(), "platform": platform.platform(),
                              "packages": {name: importlib.metadata.version(name) for name in
                                           ("langchain", "langchain-core", "pydantic")}},
              "development_metadata_only": dev_before, "development_observed": dev_after,
              "extension_metadata_only": ext_before, "extension_initial": ext_after,
              "extension_after_counterexample": ext_later, "new_registration": newly_registered,
              "real_rosa": native, "scale": scales,
              "costs": {"fixture_validation_dispatches": extra_calls,
                        "real_calculation_validation_dispatches": native["pure_calculation_dispatches"],
                        "fallback_dispatches": len(fallback_log), "fallback_log": fallback_log,
                        "engine_initiated_dispatches": 0, "llm_calls": 0, "paid_api_calls": 0,
                        "note": "Validation calls are experiment overhead; passive production observations would already be paid."},
              "observation_ingest": percentiles([r["observe_ns"] for r in raw if "observe_ns" in r]),
              "sources": {p.name: sha(p) for p in sorted(HERE.glob("*.py"))}}
    after = preservation()
    result["preservation"] = {"unchanged": before == after, "before": before, "after": after}
    (args.output / "observations.jsonl").write_text("".join(json.dumps(r, sort_keys=True) + "\n" for r in raw))
    (args.output / "results.json").write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    assert before == after, "pre-existing file or protected branch changed"
    # Visible output is deliberately compact; full field witnesses stay in JSON.
    print(json.dumps({"output": str(args.output), "development": dev_after["empirical_support"],
                      "extension_initial": ext_after["empirical_support"],
                      "extension_later": ext_later["empirical_support"],
                      "costs": result["costs"], "preserved": before == after}, indent=2))


if __name__ == "__main__":
    main()
