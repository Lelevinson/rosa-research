"""Analysis tables of the exam draft (sections 5 and 5b), computed from a run's full results logs. CPU only. Stdlib only.
  python exam_tables.py --run-name NAME [--primary M --baseline E1] [--bootstrap 5000]
Writes TABLES_<run>.md and episode_times_<run>.json next to the compact results (aggregates only: no task id, no answer).
Tables: (1) per system and model, with a pooled row: episodes, supported, requests, tokens, native operations, ending classes; (2) totals with and without capped episodes;
(3) the primary comparison: paired supported difference and token ratio with a cluster bootstrap over TASKS; (4) requests per supported completion; (5) episode wall times per system and model; (6) GPU contention frequency per machine and model."""
import argparse
import json
import random
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import queue_core as Q  # noqa: E402

CLASSES = ["supported", "unsupported", "no_answer", "validation_abort", "iteration_cap", "backend_error", "timeout", "infrastructure"]
CAPPED = {"iteration_cap", "backend_error", "timeout", "no_answer", "validation_abort"}  # the union used for the "with / without capped" totals; the single classes are always shown


def load(run_name):
    rows = []
    for path in sorted((Q.ARTIFACTS / run_name).glob("RESULTS_LOG_*.jsonl")):
        rows += [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    for r in rows:
        r["ending"] = Q.ending_class(r)
        r["supported_flag"] = bool(r.get("supported_complete"))
        r["tokens"] = (r.get("input_tokens") or 0) + (r.get("output_tokens") or 0)
    return rows


def load_contended(run_name):
    rows = []
    for path in sorted((Q.ARTIFACTS / run_name).glob("CONTENDED_LOG_*.jsonl")):
        rows += [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return rows


def summary(rows):
    n = len(rows)
    endings = Counter(r["ending"] for r in rows)
    return dict(episodes=n, supported=sum(r["supported_flag"] for r in rows), requests=sum(r.get("llm_requests") or 0 for r in rows), input_tokens=sum(r.get("input_tokens") or 0 for r in rows),
                output_tokens=sum(r.get("output_tokens") or 0 for r in rows), native_ops=sum(r.get("native_ops") or 0 for r in rows), endings={c: endings.get(c, 0) for c in CLASSES})


def cluster_bootstrap(cells, systems_pair, draws, seed=20261119):
    """cells: {(pool, task, model, seed): {system: row}}. Resample TASKS with replacement; a task carries all its models and seeds. Returns dict of intervals (or None)."""
    primary, baseline = systems_pair
    by_task = defaultdict(list)
    for key, pair in cells.items():
        if primary in pair and baseline in pair:
            by_task[(key[0], key[1])].append(pair)
    tasks = list(by_task)
    if len(tasks) < 2:
        return None, len(tasks)
    rng = random.Random(seed)
    diffs, ratios = [], []
    for _ in range(draws):
        sample = [t for _ in tasks for t in [rng.choice(tasks)]]
        pairs = [p for t in sample for p in by_task[t]]
        diffs.append(100 * sum(p[primary]["supported_flag"] - p[baseline]["supported_flag"] for p in pairs) / len(pairs))
        den = sum(p[baseline]["tokens"] for p in pairs)
        if den:
            ratios.append(sum(p[primary]["tokens"] for p in pairs) / den)
    diffs.sort(); ratios.sort()
    q = lambda xs, f: xs[min(len(xs) - 1, int(f * len(xs)))]
    return dict(diff_points=(q(diffs, 0.025), q(diffs, 0.975)), token_ratio=(q(ratios, 0.025), q(ratios, 0.975)) if ratios else None), len(tasks)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run-name", required=True)
    parser.add_argument("--primary", default="M")
    parser.add_argument("--baseline", default="E1")
    parser.add_argument("--bootstrap", type=int, default=5000)
    args = parser.parse_args()
    rows = load(args.run_name)
    contended = load_contended(args.run_name)
    if not rows and not contended:
        sys.exit("no rows")
    out = Q.COMPACT_ROOT / args.run_name
    out.mkdir(parents=True, exist_ok=True)
    systems = sorted({r["system"] for r in rows})
    models = sorted({r["model"] for r in rows})
    lines = [f"# Exam tables: run {args.run_name}", "", f"{len(rows)} episodes, systems {systems}, models {models}. Aggregates only. Generated by `exam_queue/exam_tables.py`; "
             "development fixtures unless the run says otherwise.", ""]

    def table(title, header, body):
        lines.extend([f"## {title}", "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(str(x) for x in row) + " |" for row in body] + [""])

    body = []
    for system in systems:
        for model in models + ["pooled"]:
            sel = [r for r in rows if r["system"] == system and (model == "pooled" or r["model"] == model)]
            if not sel:
                continue
            s = summary(sel)
            body.append([system, model, s["episodes"], f"{s['supported']} ({100 * s['supported'] / s['episodes']:.0f}%)", s["requests"], s["input_tokens"], s["output_tokens"], s["native_ops"],
                         " / ".join(f"{c[:6]} {s['endings'][c]}" for c in CLASSES if s["endings"][c])])
    table("1. Per system and model (pooled row last of each system)", ["system", "model", "episodes", "supported", "requests", "input tokens", "output tokens", "native ops", "ending classes"], body)

    body = []
    for system in systems:
        sel = [r for r in rows if r["system"] == system]
        keep = [r for r in sel if r["ending"] not in CAPPED]
        a, b = summary(sel), summary(keep)
        body.append([system, a["episodes"], f"{a['supported']}", a["requests"], a["input_tokens"] + a["output_tokens"], b["episodes"], f"{b['supported']}", b["requests"], b["input_tokens"] + b["output_tokens"], a["episodes"] - b["episodes"]])
    table("2. Totals with all episodes and without capped ones (capped = iteration cap, backend error, timeout, no answer)", ["system", "episodes (all)", "supported", "requests", "tokens", "episodes (without capped)", "supported", "requests", "tokens", "capped episodes"], body)

    cells = defaultdict(dict)
    for r in rows:
        cells[(r["pool"], r["task"], r["model"], r["seed"])][r["system"]] = r
    if args.primary in systems and args.baseline in systems:
        pairs = [p for p in cells.values() if args.primary in p and args.baseline in p]
        both = sum(p[args.primary]["supported_flag"] and p[args.baseline]["supported_flag"] for p in pairs)
        only_p = sum(p[args.primary]["supported_flag"] and not p[args.baseline]["supported_flag"] for p in pairs)
        only_b = sum(p[args.baseline]["supported_flag"] and not p[args.primary]["supported_flag"] for p in pairs)
        neither = len(pairs) - both - only_p - only_b
        interval, n_tasks = cluster_bootstrap(cells, (args.primary, args.baseline), args.bootstrap)
        diff = 100 * (only_p - only_b) / len(pairs) if pairs else float("nan")
        tok_p = sum(p[args.primary]["tokens"] for p in pairs); tok_b = sum(p[args.baseline]["tokens"] for p in pairs)
        req_p = sum(p[args.primary].get("llm_requests") or 0 for p in pairs); req_b = sum(p[args.baseline].get("llm_requests") or 0 for p in pairs)
        table(f"3. Primary comparison {args.primary} against {args.baseline} (paired cells; cluster bootstrap over tasks, {args.bootstrap} draws)",
              ["paired cells", "tasks", "both supported", f"{args.primary} only", f"{args.baseline} only", "neither", "supported difference (points)", "95% interval (points)", "token ratio of totals", "95% interval", "request ratio"],
              [[len(pairs), n_tasks, both, only_p, only_b, neither, f"{diff:+.1f}", "n/a (fewer than 2 tasks)" if interval is None else f"{interval['diff_points'][0]:+.1f} to {interval['diff_points'][1]:+.1f}",
                f"{tok_p / tok_b:.3f}" if tok_b else "n/a", "n/a" if not interval or not interval["token_ratio"] else f"{interval['token_ratio'][0]:.3f} to {interval['token_ratio'][1]:.3f}", f"{req_p / req_b:.3f}" if req_b else "n/a"]])
        if interval is not None and n_tasks < 10:
            lines.extend([f"*Only {n_tasks} tasks: the bootstrap interval is illustrative, not a confidence statement.*", ""])
        body = []
        for model in models + ["pooled"]:
            drow = [model]
            for system in (args.primary, args.baseline):
                sel = [p[system] for p in pairs if model == "pooled" or p[system]["model"] == model]
                sup = sum(r["supported_flag"] for r in sel)
                drow += [f"{sup}/{len(sel)}", f"{sum(r.get('llm_requests') or 0 for r in sel) / sup:.1f}" if sup else "n/a", f"{sum(r['tokens'] for r in sel) / sup:,.0f}" if sup else "n/a"]
            body.append(drow)
        table("4. Cost per supported completion (paired cells)", ["model", f"{args.primary} supported", "requests per supported", "tokens per supported", f"{args.baseline} supported", "requests per supported", "tokens per supported"], body)
    times, body = {}, []
    for system in systems:
        for model in models:
            sel = [r["wall_seconds"] for r in rows if r["system"] == system and r["model"] == model and r.get("wall_seconds") is not None]
            if sel:
                times[f"{system}|{model}"] = dict(n=len(sel), median_s=round(statistics.median(sel), 1), mean_s=round(statistics.mean(sel), 1), max_s=round(max(sel), 1), total_s=round(sum(sel), 1))
                body.append([system, model, len(sel), f"{statistics.median(sel):.0f}", f"{statistics.mean(sel):.0f}", f"{max(sel):.0f}", f"{sum(sel) / 60:.1f}"])
    table("5. Episode wall time in seconds (to compare machines later; same cells, same settings)", ["system", "model", "episodes", "median", "mean", "max", "total minutes"], body)
    body = []
    for machine in sorted({r["machine"] for r in rows} | {r["machine"] for r in contended}):
        for model in sorted(set(models) | {r["model"] for r in contended}):
            clean = [r for r in rows if r["machine"] == machine and r["model"] == model]
            bad = [r for r in contended if r["machine"] == machine and r["model"] == model]
            started = len(clean) + len(bad)
            if not started:
                continue
            unknown = sum((r.get("gpu_state") or {}).get("state", "not_recorded") != "ok" for r in clean)
            med = lambda xs: f"{statistics.median(xs):.0f}" if xs else "n/a"
            body.append([machine, model, started, len(bad), f"{100 * len(bad) / started:.1f}%", unknown, med([r["wall_seconds"] for r in bad if r.get("wall_seconds")]), med([r["wall_seconds"] for r in clean if r.get("wall_seconds")])])
    table("6. GPU contention frequency (contended = infrastructure failure by the frozen rule in gpu_state.py; those cells were run again; `unknown` = clean rows without GPU samples, e.g. recovered after a crash)",
          ["machine", "model", "episodes started", "contended", "frequency", "clean rows with unknown GPU state", "median wall s, contended", "median wall s, clean"], body)
    machines = sorted({r["machine"] for r in rows})
    (out / f"episode_times_{args.run_name}.json").write_text(json.dumps(dict(run=args.run_name, machines=machines, by_system_model=times, total_minutes=round(sum(r.get("wall_seconds") or 0 for r in rows) / 60, 1)), indent=1))
    (out / f"TABLES_{args.run_name}.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
