"""Stage 1 exam spec and plan generator (DRAFT, nothing hashed or frozen). Writes `exam_spec_stage1_DRAFT.json` and `MODEL_DIGESTS_DRAFT.json` next to this file.

  uv run python research/studies/final_exam_draft_20261118/freeze_package_20261121/make_exam_spec.py write [OLLAMA_URL]    (digests are read from Ollama /api/tags)
  uv run python research/studies/final_exam_draft_20261118/freeze_package_20261121/make_exam_spec.py counts                 (cell counts with 76 synthetic task ids; opens no custodian file)

Design (PROTOCOL_DRAFT.md revision 4 sections 9c, 9d; owner order for the laptop queue, 2026-11-21):
  tier 1  EX-M and E1 on held-out v2, 4 core models, seeds 1-3           (the primary comparison)
  tier 2  S0, F and MT on held-out v2, 4 core models, seeds 1-3        (F: Forge 0.10.1 as released via its queue adapter; MT: MetaTool mechanism ported from the released source, not the original package)
  tier 3  ablations EX-NO_MENU, EX-NO_FINISH, EX-NO_ERRORTEXT on held-out v2, 4 core models, seeds 1-3
  tier 4  extra models llama3.1:8b, ministral-3:8b, granite4.2:8b, EX-M and E1 only, seeds 1-3 (descriptive)
Expected cells (76 tasks): 1,824 + 2,736 + 2,736 + 1,368 = 8,664 = 7,296 core + 1,368 extras. The pool is the custodian's list named by the environment variable below: it is read at run time
and never stored in a tracked file. Cell order inside a tier comes from the queue (seed, seeded task shuffle, model, seeded system shuffle inside the pair); the master seed is a DRAFT value.
"""
import json
import os
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
QUEUE = HERE.parent / "exam_queue"
CORE_MODELS = ["lfm3:1.7b", "qwen3.5:9b", "gpt-oss:20b", "bonsai-2:4b"]
EXTRA_MODELS = ["llama3.1:8b", "ministral-3:8b", "granite4.2:8b"]
SEEDS = [1, 2, 3]
MASTER_SEED = 20261122  # DRAFT: the freeze fixes it
POOL = "held_out_v2"
POOL_ENV = "ROSA_HELDOUT_V2_TASKS"


def build_spec():
    tier = lambda name, systems, models=None: dict(name=name, systems=systems, pools=[POOL], seeds=SEEDS, **({"models": models} if models else {}))
    return {"name": "stage1_exam_DRAFT", "master_seed": MASTER_SEED, "temperature": 0.7, "models": CORE_MODELS,
            "_status": "DRAFT, NOT FROZEN, NOT HASHED. Stage 1 only (held-out v2). Generated by make_exam_spec.py; the freeze hashes this file and records the digests of MODEL_DIGESTS_DRAFT.json.",
            "pools": {POOL: {"tasks_file_env": POOL_ENV}},
            "tiers": [tier("tier1_M_vs_E1", ["EX-M", "E1"]),
                      tier("tier2_S0_F_MT", ["S0", "F", "MT"]),
                      tier("tier3_ablations", ["EX-NO_MENU", "EX-NO_FINISH", "EX-NO_ERRORTEXT"]),
                      tier("tier4_extra_models", ["EX-M", "E1"], EXTRA_MODELS)],
            "queue": {"block_size": 48, "heartbeat_seconds": 30, "min_free_gb": 20, "quarantine_after": 3}}


def build_final_specs():
    """The two FROZEN Stage 1 specs (2026-11-22). F is split into its own spec because the custodian launcher refuses a whole spec that contains a system without a held-out adapter
    (queue_bridge.load_spec) and F has none yet; tier 1 must not wait for it. Same cells as the approved design: main 7,752 + F 912 = 8,664.
    exam_spec_stage1.json   tier 1 EX-M, E1 | tier 2 S0, MT | tier 3 ablations | tier 4 extra models (EX-M, E1)         run now on the laptop
    exam_spec_stage1_F.json tier 2b F (core models, seeds 1-3)                                                         refused until the held-out F adapter is ready"""
    tier = lambda name, systems, models=None: dict(name=name, systems=systems, pools=[POOL], seeds=SEEDS, **({"models": models} if models else {}))
    common = {"temperature": 0.7, "models": CORE_MODELS, "master_seed": MASTER_SEED, "pools": {POOL: {"tasks_file_env": POOL_ENV}}, "queue": {"block_size": 48, "heartbeat_seconds": 30, "min_free_gb": 20, "quarantine_after": 3}}
    main = dict(common, name="stage1_exam", _status="FROZEN by FREEZE.json (2026-11-22). Stage 1 only (held-out v2). Generated by make_exam_spec.py final. F is in exam_spec_stage1_F.json.",
                tiers=[tier("tier1_M_vs_E1", ["EX-M", "E1"]), tier("tier2_S0_MT", ["S0", "MT"]), tier("tier3_ablations", ["EX-NO_MENU", "EX-NO_FINISH", "EX-NO_ERRORTEXT"]),
                       tier("tier4_extra_models", ["EX-M", "E1"], EXTRA_MODELS)])
    forge = dict(common, name="stage1_exam_F", _status="FROZEN by FREEZE.json (2026-11-22). System F only; NOT RUNNABLE until the custodian bridge has a held-out F adapter (the bridge refuses the spec until then).",
                 tiers=[tier("tier2b_F", ["F"])])
    return main, forge


def digests(url):
    tags = json.load(urllib.request.urlopen(url.rstrip("/") + "/api/tags", timeout=15))
    have = {m["name"]: m["digest"] for m in tags["models"]}
    missing = [m for m in CORE_MODELS + EXTRA_MODELS if m not in have]
    if missing:
        raise SystemExit(f"models not present on {url}: {missing}")
    return {m: have[m] for m in CORE_MODELS + EXTRA_MODELS}


def counts():
    sys.path.insert(0, str(QUEUE))
    import queue_core as Q
    spec = build_spec()
    tasks = {f"synthetic_{i:02d}": "stage3" for i in range(76)}
    spec["pools"] = {POOL: {"tasks": tasks}}
    cells = Q.build_cells(spec)
    per_tier = {}
    for c in cells:
        per_tier[c["tier"]] = per_tier.get(c["tier"], 0) + 1
    return per_tier, len(cells)


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else "counts"
    if command == "final":
        main_spec, forge_spec = build_final_specs()
        (HERE / "exam_spec_stage1.json").write_text(json.dumps(main_spec, indent=1) + "\n")
        (HERE / "exam_spec_stage1_F.json").write_text(json.dumps(forge_spec, indent=1) + "\n")
        print("written final specs, master seed", MASTER_SEED)
    elif command == "write":
        url = sys.argv[2] if len(sys.argv) > 2 else os.environ.get("ROSA_OLLAMA_URL", "http://172.30.80.1:11434")
        (HERE / "exam_spec_stage1_DRAFT.json").write_text(json.dumps(build_spec(), indent=1) + "\n")
        (HERE / "MODEL_DIGESTS_DRAFT.json").write_text(json.dumps(dict(source=url, note="laptop Ollama /api/tags, 2026-11-21; the lab's copies must be compared at the pre-run gate", digests=digests(url)), indent=1) + "\n")
        print("written")
    else:
        print(counts())
