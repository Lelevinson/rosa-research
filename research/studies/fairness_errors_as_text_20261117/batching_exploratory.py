"""EXPLORATORY (not in the frozen protocol): requests with two or more tool calls in the saved fairness traces. CPU only, reads saved traces.
A request = one model response (model_end); its calls = the tool_start events until the next model_end. Reference rows: the stock pilot arms S0 and A1 (same executor, no errors-as-text).
uv run python batching_exploratory.py -> BATCHING_EXPLORATORY.md"""
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
STUDIES = HERE.parent
REPO = HERE.parents[2]
MODELS = ["lfm3:1.7b", "qwen3.5:9b", "gpt-oss:20b", "bonsai-2:4b"]
rows = lambda p: [json.loads(l) for l in Path(p).read_text().splitlines() if l.strip()]


def calls_per_request(trace):
    counts, current = [], None
    for line in (REPO / trace).read_text().splitlines():
        e = json.loads(line)
        if e["kind"] == "model_end":
            current = [0]
            counts.append(current)
        elif e["kind"] == "tool_start" and current is not None:
            current[0] += 1
    return [c[0] for c in counts]


def tally(rs):
    out = defaultdict(lambda: dict(episodes=0, requests=0, requests_with_calls=0, multi=0, episodes_with_multi=0, max_calls=0, calls=0))
    for r in rs:
        counts = calls_per_request(r["trace_path"])
        for key in (r["model"], "all"):
            t = out[key]
            t["episodes"] += 1
            t["requests"] += len(counts)
            t["requests_with_calls"] += sum(c >= 1 for c in counts)
            t["calls"] += sum(counts)
            t["multi"] += sum(c >= 2 for c in counts)
            t["episodes_with_multi"] += any(c >= 2 for c in counts)
            t["max_calls"] = max([t["max_calls"], *counts])
    return out


full = [r for r in rows(HERE / "RESULTS_LOG.jsonl") if r.get("phase") == "full"]
groups = {"E0 (verbatim prompt + errors as text)": [r for r in full if r["arm"] == "E0"], "E1 (A1 prompt + errors as text)": [r for r in full if r["arm"] == "E1"],
          "S0 stock, verbatim (reference)": [r for r in rows(STUDIES / "s0_dev_20261116/RESULTS_LOG.jsonl") if r.get("phase") == "full"],
          "A1 stock, deconflicted (reference)": [r for r in rows(STUDIES / "small_model_harness_20261115/RESULTS_LOG.jsonl") if r["arm"] == "A1" and r.get("phase") != "smoke"]}
lines = ["# Exploratory: requests with two or more tool calls (NOT in the frozen protocol)", "",
         "Counted from saved traces, one request = one model response, calls = tool calls of that response. Generated by `batching_exploratory.py`. Exploratory: not part of the frozen protocol, no bar, descriptive only.", "",
         "| arm | model | episodes | requests | requests with 2+ calls | share of requests | episodes with 2+ | most calls in one request |", "|---|---|---:|---:|---:|---:|---:|---:|"]
result = {}
for name, rs in groups.items():
    t = tally(rs)
    result[name] = {k: dict(v) for k, v in t.items()}
    for key in MODELS + ["all"]:
        v = t[key]
        lines.append(f"| {name} | {key} | {v['episodes']} | {v['requests']} | {v['multi']} | {v['multi'] / v['requests']:.1%} | {v['episodes_with_multi']} | {v['max_calls']} |")
(HERE / "BATCHING_EXPLORATORY.md").write_text("\n".join(lines) + "\n")
(HERE / "batching_exploratory.json").write_text(json.dumps(result, indent=1))
print("\n".join(lines))
